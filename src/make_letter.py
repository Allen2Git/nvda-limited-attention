'''Generate the "why this topic" letter to the professor with the same
standard Chinese academic formatting as the main paper.'''
import os
import sys

from docx.enum.text import WD_ALIGN_PARAGRAPH

HERE = os.path.dirname(__file__)
sys.path.insert(0, HERE)
from docx_style import new_doc, add_title, add_subtitle, add_h1, add_body

ROOT = os.path.abspath(os.path.join(HERE, '..'))
OUT = os.path.join(ROOT, 'paper', '选题说明_给老师.docx')
os.makedirs(os.path.dirname(OUT), exist_ok=True)

doc = new_doc()

add_title(doc, '选题说明：为什么我们选择研究 NVIDIA 财报的有限注意力效应')
add_subtitle(doc, '清华-Cornell MBA · 数据分析与决策 II · 案例作业说明')

add_h1(doc, '一、选题的来由')
add_body(doc,
    '本小组在确定选题过程中经历了几次重要调整，最终落在「NVIDIA 财报后的'
    '有限注意力效应」这一主题。选题的曲折本身正是数据分析与决策方法论训练的'
    '一部分——我们希望借此简要向老师说明我们在选题过程中的思考。'
)
add_body(doc,
    '最初，我们被 NVIDIA 在 2023–2024 年 AI 浪潮中的惊人表现所吸引。'
    '作为 MBA 学生，我们对以下问题有天然的兴趣：这家公司的短期股价波动——'
    '财报日的暴涨暴跌、GTC 大会的市场反应、员工 RSU 归属日的供给压力、'
    '甚至是 10 拆 1 拆股前后的市场结构变化——在多大程度上反映了基本面？'
    '又在多大程度上反映了散户的情绪与行为偏差？这样的问题既有学术根源，'
    '也有切实的投资决策意义。'
)
add_body(doc,
    '我们最初尝试过三个不同角度：（1）NVDA 10:1 拆股的断点回归，'
    '检验拆股是否如经典文献预测那样通过降低散户心理门槛推高成交量；'
    '（2）2024 年 AMZN 与 NVDA 相继被纳入道琼斯指数的事件研究，'
    '检验经典的 index inclusion premium 是否仍然成立；'
    '（3）NVDA 财报日及其前后的异常成交量分析，从多事件维度'
    '（财报、GTC、股东信、RSU）检验散户注意力滞后。'
)
add_body(doc,
    '在对数据进行初步探索之后，我们发现前两个方向各有其方法论上的不足——'
    '拆股事件与 AI 财报周期高度捆绑，无法干净识别拆股本身的因果效应；'
    '道指纳入在两个案例上呈现了极强的异质性'
    '（NVDA 显著、AMZN 基本无效应），'
    '但以仅有的两个事件做结论具有明显的局限。相比之下，'
    '以 NVDA 2020–2026 年 24 次季度财报为样本、'
    '聚焦于单一事件类型（财报）、单一标的（NVDA），'
    '研究的边界最清晰、样本最均质、数据可得性最好——'
    '这就是我们最终锁定的研究问题。'
)

add_h1(doc, '二、为什么是「有限注意力」这个具体假说')
add_body(doc,
    '有限注意力假说（Hirshleifer & Teoh 2003；Barber & Odean 2008）是'
    '行为金融学中最经典、最有实证根基的假说之一。它的核心预测具象而可检验：'
)
add_body(doc,
    '盘后发布的财报，次日开盘后散户会集中涌入推动价格过冲，'
    '随后在盘中被机构套利者反转。这意味着开盘 1 小时收益应该'
    '系统性地「负预测」盘中剩余收益。',
    italic=True,
)
add_body(doc, '我们选择检验这个具体假说的三个理由：')
add_body(doc,
    '第一，它是一个可被证伪的明确预测。不是模糊地问「散户行为有影响吗」，'
    '而是具体地问「开盘 1 小时收益能否负预测盘中收益，'
    '回归系数 β₁ 是否显著为负」。'
    '这种「具象到可以画出一个系数、一个 t 值」的研究设计，'
    '是课程反复强调的方法论优点。'
)
add_body(doc,
    '第二，NVDA 是这个假说的极限压力测试。NVDA 在 2020 年代是'
    '「最受散户情绪影响」和「最受机构深度覆盖」两个极端的结合体。'
    '如果有限注意力假说在 NVDA 上仍然成立，这就是该假说最强的现代证据；'
    '反之，如果 NVDA 上找不到这个模式，其失效的叙事力就相当强。'
    '换句话说，无论结果朝哪个方向，都有研究价值。'
)
add_body(doc,
    '第三，这个问题对 MBA 同学的日常投资有直接意义。'
    '我们中很多同学都持有或关注 NVDA。'
    '理解「财报日次日开盘后发生了什么」'
    '不是学院派的练习——而是对每个人的真实交易决策都有帮助的知识。'
    '一次成功的课程作业，应该在学术严谨与实务价值之间取得平衡，'
    '我们相信这个题目做到了这一点。'
)

add_h1(doc, '三、课程方法论是如何在本研究中落地的')
add_body(doc,
    '本文集中运用了《数据分析与决策 II》课程的核心方法，'
    '将它们整合在同一个真实数据的事件研究里。具体对应关系如下：'
)
add_body(doc,
    '（1）多元 OLS 回归 + HC1 异方差稳健标准误 —— '
    '核心规范 r_mid_day = α + β₁·r_open_1h + β₂·r_overnight + ε。'
    '我们同时估计多元版与单变量版，对比系数稳定性；'
    '所有标准误均采用 HC1 估计以应对金融数据的异方差性。'
)
add_body(doc,
    '（2）事件研究设计 —— 本研究的核心识别框架。'
    '通过将「事件的发生」作为时间维度的外生冲击，'
    '比较事件窗口内的日内价格行为是否系统性地偏离正常模式。'
)
add_body(doc,
    '（3）Placebo 对照 —— 我们选取了 70 个与财报事件无关的普通交易日，'
    '用完全相同的回归规范进行估计。这一对照让我们能区分'
    '「事件效应不存在」与「效应被噪声遮蔽」——'
    '是因果识别中的关键稳健性设计。'
)
add_body(doc,
    '（4）稳健性与子样本分析 —— 将开盘段从 1 小时缩短至 30 分钟、'
    '延长至 2 小时，验证结论不依赖于特定窗口选择；'
    '按 EPS surprise 三分位切分样本，验证结论不在特定子样本上失效。'
)
add_body(doc,
    '（5）诚实的零结果讨论 —— 这是课程后半段强调的重要方法伦理。'
    '本文主要结论是 β₁ 不显著异于零（β = +0.06，t = 0.28）。'
    '我们没有追求显著性，'
    '而是充分讨论：在给定样本量下能检测到的最小效应量级、'
    '为何 placebo 对照能支持「零结果真实」的解释、'
    '以及零结果自身的实务与方法论意义。'
)

add_h1(doc, '四、我们希望通过这篇论文表达什么')
add_body(doc,
    '坦率地说，我们这篇论文测到的是一个零结果——'
    '有限注意力假说预测的「开盘过冲 + 盘中反转」模式，'
    '在 2020–2026 年的 NVDA 财报样本上不存在。'
    '我们很清楚，这类零结果在传统学术期刊上不容易发表，'
    '但作为 MBA 课程作业，我们相信它有以下三层价值：'
)
add_body(doc,
    '一是方法论价值。一个干净识别出的零结果，'
    '比一个勉强显著的正向结果更能展示我们对方法论的掌握。'
    '如果我们看到 β = +0.06 然后'
    '写成「弱反转」、或者刻意调整窗口以获得显著结果，'
    '那是对数据的不尊重；'
    '我们选择如实报告、深入讨论其含义，这本身是研究伦理的体现。'
)
add_body(doc,
    '二是机制价值。零结果并不等于没话说。'
    '我们在论文第 5 节通过三项'
    '2020 年代市场结构变化——盘前交易机构化、社交媒体即时传播、'
    'Robinhood 式 App 的盘前权限——解释了为什么有限注意力假说'
    '在今天的 NVDA 上会失效。'
    '这是将市场微观结构演进与行为金融假说联系起来的尝试。'
)
add_body(doc,
    '三是实务价值。作为 MBA 学生，'
    '我们的研究输出最终要服务于管理与投资决策。'
    '论文第 6 节明确指出：IR 团队不必再为「散户次日过度反应」担忧；'
    '事件驱动型交易者过去依赖的朴素规则'
    '（开盘卖出、开盘 1 小时后买入）'
    '在 NVDA 这类大盘 AI 龙头上已不再成立；'
    '普通散户应将长期持有作为核心策略，'
    '避开财报日次日开盘的「散户陷阱小时」。'
    '这些都是可以直接落到个人财务决策的建议。'
)
add_body(doc,
    '我们希望老师能看到的，不仅是一个跑通的回归和几张图，更是：'
    '我们在数据面前保持诚实、在方法上追求严谨、'
    '在解释上结合真实市场动态、在结论上回归人本身的决策需要。'
    '如果这篇论文能让课堂上的同学在自己下一次面对 NVDA 财报的开盘屏幕时，'
    '多一份冷静和多一份方法论自觉，我们的工作就有意义。'
)

# 落款
add_body(doc, '', indent=False)
add_body(doc, '小组成员敬上', indent=False, align=WD_ALIGN_PARAGRAPH.RIGHT)

doc.save(OUT)
print('Saved:', OUT)
